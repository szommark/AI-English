export type CourseCopyKey = keyof typeof COPY

export function useCourseCopy() {
  const { lang } = useLanguage()
  const c = useCallback(
    (key: CourseCopyKey, vars?: Record<string, string | number>) => {
      let s: string = COPY[key][lang]
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
      return s
    },
    [lang],
  )
  const kind = useCallback((k: ModuleKind) => COPY[`kind_${k}`][lang], [lang])
  return { c, kind, lang }
}
