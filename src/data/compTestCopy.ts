export type CompCopyKey = keyof typeof COPY

export function useCompCopy() {
  const { lang } = useLanguage()
  const c = useCallback(
    (key: CompCopyKey, vars?: Record<string, string | number>) => {
      let s: string = COPY[key][lang]
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
      return s
    },
    [lang],
  )
  return { c, lang }
}
